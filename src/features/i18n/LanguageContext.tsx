const LanguageContext = createContext<{ language: Language; setLanguage: (language: Language) => void } | null>(null);

function getInitialLanguage(): Language {
  if (typeof window === "undefined") return "tr";
  try {
    const saved = window.localStorage.getItem("e-store-language");
    activeLanguage = saved === "tr" || saved === "en"
      ? saved
      : window.navigator.language.toLowerCase().startsWith("tr") ? "tr" : "en";
  } catch {
    activeLanguage = window.navigator.language.toLowerCase().startsWith("tr") ? "tr" : "en";
  }
  return activeLanguage;
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(getInitialLanguage);
  const setLanguage = (next: Language) => {
    activeLanguage = next;
    try { window.localStorage.setItem("e-store-language", next); } catch { /* Keep the selected language for this session. */ }
    setLanguageState(next);
  };
  useEffect(() => {
    document.documentElement.lang = language;
    try { window.localStorage.setItem("e-store-language", language); } catch { /* Storage may be disabled by the browser. */ }
  }, [language]);
  const value = useMemo(() => ({ language, setLanguage }), [language]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const value = useContext(LanguageContext);
  if (!value) throw new Error("useLanguage must be used within LanguageProvider");
  return value;
}

export function translate(source: string, language?: Language): string {
  const current = language ?? activeLanguage;
  const key = source.trim().replaceAll("&lt;", "<").replaceAll("&gt;", ">")
    .replaceAll("&bull;", "•").replaceAll("&middot;", "·").replaceAll("&rarr;", "→")
    .replaceAll("&times;", "×").replaceAll("&nbsp;", " ").replaceAll("&amp;", "&")
    .replace(/\s+/gu, " ");
  const sourceIsTurkish = /[çğıöşüİ]/iu.test(key);
  const translated = key === "ONAY"
    ? (current === "tr" ? "ONAY" : "DELETE")
    : current === "tr"
    ? (sourceIsTurkish ? key : englishToTurkish[key] ?? englishToTurkishAttributes[key] ?? key)
    : (sourceIsTurkish
      ? turkishToEnglish[key] ?? englishToTurkish[key] ?? Object.entries(englishToTurkishAttributes).find(([, value]) => value === key)?.[0]
      : englishToTurkish[key] ? key : turkishToEnglish[key] ?? key);
  if (translated === key) {
    return source.replaceAll("&lt;", "<").replaceAll("&gt;", ">")
      .replaceAll("&bull;", "•").replaceAll("&middot;", "·").replaceAll("&rarr;", "→")
      .replaceAll("&times;", "×").replaceAll("&nbsp;", " ").replaceAll("&amp;", "&");
  }
  const leading = source.match(/^\s*/)?.[0] ?? "";
  const trailing = source.match(/\s*$/)?.[0] ?? "";
  return `${leading}${translated}${trailing}`;
}

